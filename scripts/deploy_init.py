#!/usr/bin/env python3
"""Generate a private Evaluation deployment aligned to a RAG Lab environment."""

from __future__ import annotations

import argparse
import os
import tempfile
from pathlib import Path


def read_env(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip()
    return values


def deployment_values(raglab: dict[str, str], port: int, host: str, project_name: str = "agent-evaluation") -> dict[str, str]:
    tenant_password = raglab.get("RAGLAB_TENANT_A_PASSWORD", "")
    if not tenant_password:
        raise ValueError("RAGLAB_TENANT_A_PASSWORD is missing from the RAG Lab deployment environment")
    api_port = int(raglab.get("RAGLAB_API_PORT", "8080"))
    agent_port = int(raglab.get("RAGLAB_AGENT_PORT", "8090"))
    return {
        "COMPOSE_PROJECT_NAME": project_name,
        "AGENT_EVALUATION_PORT": str(port),
        "AGENT_EVALUATION_URL": f"http://127.0.0.1:{port}",
        "RAGLAB_API_URL": f"http://host.docker.internal:{api_port}",
        "RAGLAB_AGENT_URL": f"http://host.docker.internal:{agent_port}",
        "RAGLAB_HOST_API_URL": f"http://127.0.0.1:{api_port}",
        "RAGLAB_HOST_AGENT_URL": f"http://127.0.0.1:{agent_port}",
        "AGENT_EVALUATION_EMAIL": "alice@tenant-a.local",
        "AGENT_EVALUATION_PASSWORD": tenant_password,
        "EVALUATION_MODEL_BASE_URL": "https://api.deepseek.com",
        "EVALUATION_MODEL": "deepseek-chat",
        "EVALUATION_MAX_TURNS": "6",
        "EVALUATION_MAX_TOOL_CALLS": "8",
        "EVALUATION_TIMEOUT_MS": "90000",
        "EVALUATION_CORS_ORIGINS": ",".join(
            f"http://{name}:{port}" for name in dict.fromkeys((host, "localhost", "127.0.0.1"))
        ),
    }


def write_private(path: Path, content: str, force: bool) -> None:
    if path.exists() and not force:
        raise FileExistsError(f"{path} already exists")
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent, text=True)
    try:
        os.fchmod(descriptor, 0o600)
        with os.fdopen(descriptor, "w", encoding="utf-8") as stream:
            stream.write(content)
        os.replace(temporary, path)
        path.chmod(0o600)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def render_env(values: dict[str, str]) -> str:
    return "\n".join([
        "# Generated by scripts/deploy_init.py. Keep this file private.",
        "# The evaluator model API key is intentionally excluded.",
        *(f"{key}={value}" for key, value in values.items()),
        "",
    ])


def render_credentials(values: dict[str, str], host: str) -> str:
    return "\n".join([
        "Agent Evaluation portable deployment",
        "====================================",
        f"Platform: http://{host}:{values['AGENT_EVALUATION_PORT']}",
        f"Studio: http://{host}:{values['AGENT_EVALUATION_PORT']}/studio",
        f"Login: {values['AGENT_EVALUATION_EMAIL']} / {values['AGENT_EVALUATION_PASSWORD']}",
        "",
        "The model API key is inherited from the process environment and is not stored.",
        "",
    ])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--raglab-env", default="../rag-evolution-lab/.env")
    parser.add_argument("--output", default=".env")
    parser.add_argument("--credentials-output", default=".deploy/credentials.txt")
    parser.add_argument("--port", type=int, default=18200)
    parser.add_argument("--project-name", default="agent-evaluation")
    parser.add_argument("--host", default="localhost")
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()
    if args.port < 1 or args.port > 65535:
        raise SystemExit("port must be between 1 and 65535")
    source = Path(args.raglab_env).expanduser().resolve()
    if not source.exists():
        raise SystemExit(f"RAG Lab deployment environment not found: {source}")
    try:
        if not args.project_name.replace("-", "").replace("_", "").isalnum():
            raise ValueError("project name may contain only letters, numbers, hyphens and underscores")
        values = deployment_values(read_env(source), args.port, args.host, args.project_name)
    except (ValueError, TypeError) as error:
        raise SystemExit(str(error)) from error
    output = Path(args.output).expanduser().resolve()
    credentials = Path(args.credentials_output).expanduser().resolve()
    if not args.force and (output.exists() or credentials.exists()):
        existing = output if output.exists() else credentials
        raise SystemExit(f"{existing} already exists; reuse it or pass --force")
    write_private(output, render_env(values), args.force)
    write_private(credentials, render_credentials(values, args.host), args.force)
    print(f"evaluation_env={output}")
    print(f"credentials={credentials}")
    print("model_keys_written=false")


if __name__ == "__main__":
    main()
